import * as fs from "fs";

import { SpdxFile } from "./file";
import { IRelationship } from "./relationship";

/** COPYING, LICENSE and LICENCE, optionally followed by a dash or dot and more (e.g. LICENSE-MIT, COPYING.md) */
const LICENSE_FILE_PATTERN = /^(COPYING|LICEN[CS]E)([-.].*)?$/;

/**
 * Whether the file is a Covered File (REUSE Specification 3.3, "Covered and ignored Files")
 * @param file Path relative to the project root
 * @returns False for files that need no Licensing Information of their own
 */
function isCoveredFile(file: string): boolean {
  const path = file.replace(/^\.\//, "");
  const name = path.split("/").pop() ?? path;
  return !(
    path.endsWith(".license") ||
    name === "REUSE.toml" ||
    path.startsWith(".reuse/") ||
    path.includes("LICENSES/") ||
    LICENSE_FILE_PATTERN.test(name) ||
    isSymlinkOrEmpty(path)
  );
}

/**
 * Whether the file is a symbolic link or has no data (zero bytes); neither is a Covered File
 * @param path Path of the file
 * @returns True for symbolic links and empty files
 */
function isSymlinkOrEmpty(path: string): boolean {
  if (!fs.existsSync(path)) return false;
  const stat = fs.lstatSync(path);
  return stat.isSymbolicLink() || (stat.isFile() && stat.size === 0);
}

/**
 * SPDX Software Bill of Materials (SBOM)
 *
 * By default the following values are set:
 * - SPDX ID: SPDXRef-DOCUMENT
 * - SPDX Version: SPDX-2.3
 * - Document Namespace: http://spdx.org/spdxdocs/spdx-v2.3-45eae250-b782-46dd-9723-62ec3bed2a7c
 * - Data License: CC0-1.0
 *
 * @class SoftwareBillOfMaterials
 * @member SPDXID The SPDX ID of the element
 * @member spdxVersion The SPDX version
 * @member name The name of the SBOM
 * @member documentNamespace The namespace of the SBOM
 * @member dataLicense The license of the SBOM itself
 * @member creationInfo The creation information of the SBOM
 * @member relationships The relationships between the document and its elements
 * @member files The files associated with thethe SBOM
 * @see https://spdx.github.io/spdx-spec/2-document-creation-information/
 * @see https://spdx.github.io/spdx-spec/3-relationships-between-SPDX-elements/
 */
export class SoftwareBillOfMaterials {
  readonly SPDXID = "SPDXRef-DOCUMENT";
  readonly spdxVersion = "SPDX-2.3";
  name: string;
  readonly documentNamespace = "http://spdx.org/spdxdocs/spdx-v2.3-45eae250-b782-46dd-9723-62ec3bed2a7c";
  readonly dataLicense = "CC0-1.0";
  creationInfo: {
    comment: string;
    created: string;
    creators: string[];
  };
  relationships: IRelationship[] = [];
  files: SpdxFile[] = [];

  constructor(name: string, tool: string) {
    this.name = name;
    this.creationInfo = {
      comment: `Generated by ${tool}`,
      created: new Date().toISOString(),
      creators: [`Tool: ${tool}`],
    };
  }

  /**
   * Adds a file to the SBOM.
   * Additionally, this will create a DESCRIBES relationship between the SBOM and the file.
   *
   * NOTE: Files which are not Covered Files in the REUSE Specification are ignored: .license files,
   * REUSE.toml files, the .reuse/ directory, the LICENSES/ directory, and COPYING, LICENSE and LICENCE files,
   * symbolic links and empty files.
   *
   * @param file The file to add (relative to the project root)
   */
  async addFile(file: string) {
    await this.addFiles([file]);
  }

  /**
   * Adds multiple files in bulk to the SBOM, in the order given (they are parsed concurrently).
   * Files which are not Covered Files are ignored, as with addFile.
   *
   * @param files List of files to add
   */
  async addFiles(files: string[]) {
    const spdxFiles = await Promise.all(files.filter(isCoveredFile).map(file => SpdxFile.fromFile(file)));
    for (const spdxFile of spdxFiles) {
      this.files.push(spdxFile);
      this.relationships.push({
        spdxElementId: this.SPDXID,
        relationshipType: "DESCRIBES",
        relatedSpdxElement: spdxFile.SPDXID,
      });
    }
  }
}
