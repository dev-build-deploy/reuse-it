import * as crypto from "crypto";
import * as fs from "fs";

import * as reuseIt from "../src/index";
import * as spdxFile from "../src/spdx/file";

/**
 * Sets the path of the dep5 file used by the library.
 * @param dep5 Path of the dep5 file
 */
function useConfiguration(dep5: string): void {
  Object.defineProperty(spdxFile, "DEP5_FILE_PATH", { value: dep5 });
}

/**
 * The licensing information of a file, as the tests compare it.
 * @param file The file to parse
 */
async function licensingOf(
  file: string
): Promise<{ copyrightText?: string; licenseInfoInFiles: string[]; comment?: string }> {
  const spdx = await reuseIt.SpdxFile.fromFile(file);
  return { copyrightText: spdx.copyrightText, licenseInfoInFiles: spdx.licenseInfoInFiles, comment: spdx.comment };
}

/**
 * Conformance with the REUSE Specification 3.3 (https://reuse.software/spec-3.3/).
 */
describe("REUSE Specification", () => {
  test("Binary files are hashed byte for byte", async () => {
    useConfiguration("does-not-exist");
    const file = "test/spec/binary/image.png";
    const spdx = await reuseIt.SpdxFile.fromFile(file);

    const expected = crypto.createHash("SHA1").update(fs.readFileSync(file)).digest("hex");
    expect(spdx.checksums).toStrictEqual([{ algorithm: "SHA1", checksumValue: expected }]);
  });

  describe("DEP5", () => {
    beforeEach(() => useConfiguration("test/spec/dep5/spec.dep5"));

    test("The header paragraph does not apply to files", async () => {
      expect(await licensingOf("test/spec/license/uncovered.txt")).toStrictEqual({
        copyrightText: undefined,
        licenseInfoInFiles: ["NOASSERTION"],
        comment: undefined,
      });
    });

    test("A Files paragraph applies, including its Comment", async () => {
      expect(await licensingOf("test/spec/dep5/covered.txt")).toStrictEqual({
        copyrightText: "2023 Stanza Holder",
        licenseInfoInFiles: ["CC0-1.0"],
        comment: "Generated by a script.",
      });
    });

    test("DEP5 information is aggregated with the information in the file", async () => {
      expect(await licensingOf("test/spec/dep5/own-header.ts")).toStrictEqual({
        copyrightText: "2023 Stanza Holder\n2024 Own Holder",
        licenseInfoInFiles: ["CC0-1.0", "MIT"],
        comment: "Generated by a script.",
      });
    });
  });

  test("A .license file takes precedence over the file's own comment header", async () => {
    useConfiguration("does-not-exist");
    expect(await licensingOf("test/spec/license/both.ts")).toStrictEqual({
      copyrightText: "2025 Sidecar Holder",
      licenseInfoInFiles: ["CC0-1.0"],
      comment: undefined,
    });
  });
});
